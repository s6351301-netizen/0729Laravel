$input = $_GET;
if (isset($_GET['topic']) && trim($_GET['topic']) !== '') {
    $topic = trim($input['topic']);
    $count = intval($input['count']);
    $paras = intval($input['paras']);
} else {
    echo json_encode(['error' => '請輸入主題'], JSON_UNESCAPED_UNICODE);
