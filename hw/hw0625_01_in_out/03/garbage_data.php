}

if ($count < 100)  $count = 100;
if ($count > 1000) $count = 1000;
if ($paras < 1)    $paras = 1;
if ($paras > 10)   $paras = 10;

function pick_famous($famous, $topic)
{
    $sentence = $famous[array_rand($famous)];
    return str_replace('x', $topic, $sentence);
}

function pick_bosh($bosh, $topic)
{
    $sentence = $bosh[array_rand($bosh)];
    return str_replace('x', $topic, $sentence);
}

$article_paragraphs = [];
$total_chars = 0;
$chars_per_para = (int)($count / $paras);

for ($p = 0; $p < $paras; $p++) {
    $para = '';
    $para_len = 0;

    while ($para_len < $chars_per_para) {
        $rand = rand(0, 99);

        if ($rand < 20) {
            $sentence = pick_famous($famous, $topic);
        } else {
            $sentence = pick_bosh($bosh, $topic);
        }

        $para .= $sentence;
        $para_len += mb_strlen($sentence, 'UTF-8');
    }

    $article_paragraphs[] = $para;
    $total_chars += $para_len;
}


$result = [
    'topic'        => $topic,
    'count'        => $count,
    'paras'        => $paras,
    'actual_chars' => $total_chars,
    'paragraphs'   => $article_paragraphs,
];

echo json_encode($result, JSON_UNESCAPED_UNICODE);
